-- Arquivo: schema_maturidade_respostas.sql
-- Go Ladies: respostas da Maturidade, sugestões das agentes e ligação com o Drive (23/10/2026)
--
-- Precisa do schema_maturidade_e_pastas_drive.sql (já rodado em 23/10).
--
-- 1) Cada ponto ganha "O que já é dado" e "O que é hipótese" (o "O que falta
--    verificar" continua na coluna observacao) e "Respondido por".
-- 2) Histórico: toda mudança guarda a versão anterior (gatilho), então nada se perde.
-- 3) Sugestões: agentes e o Claude não mudam a resposta; deixam uma sugestão
--    que a Jú (ou a Rafaela) aceita ou descarta no CRM.
-- 4) Ligação com o Drive: a rotina das 18h compara o CRM com o documento
--    "Checklist de maturidade.md". Mudou só no CRM → vai pro documento. Mudou
--    só no documento → vem pro CRM. Mudou nos dois → fica o CRM e a versão do
--    documento aparece no ponto pra ela decidir (conflito_drive).
--
-- Funções com chave (mesma chave da Gabi, gabi_supabase.ps1):
--   sede_maturidade_ler(chave)               → pontos + sugestões pendentes
--   sede_maturidade_sugerir(chave, lista)    → [{"ponto": 3, "agente": "ester", "dado": "...", "motivo": "..."}]
--   sede_maturidade_sincronizar(chave, lista)→ uso da rotina das 18h
--
-- Rodar uma vez em: Supabase (go-ladies-crm) → SQL Editor → New query →
-- colar tudo → Run. Pode rodar de novo sem estragar nada.

-- ── 1) Campos novos ────────────────────────────────────────────────────
alter table public.sede_maturidade add column if not exists dado text;
alter table public.sede_maturidade add column if not exists hipotese text;
alter table public.sede_maturidade add column if not exists respondido_por text;
alter table public.sede_maturidade add column if not exists sincronizado_em timestamptz;   -- última vez que a rotina alinhou com o Drive
alter table public.sede_maturidade add column if not exists drive_hash text;               -- impressão digital do texto do documento naquela vez
alter table public.sede_maturidade add column if not exists conflito_drive jsonb;          -- versão do documento quando os dois mudaram

-- ── 2) Histórico ───────────────────────────────────────────────────────
create table if not exists public.sede_maturidade_historico (
  id bigint generated by default as identity primary key,
  maturidade_id bigint not null references public.sede_maturidade(id) on delete cascade,
  situacao text, dado text, hipotese text, observacao text, onde text, link text,
  respondido_por text,
  valido_ate timestamptz not null default now()     -- quando essa versão foi trocada
);
create index if not exists sede_maturidade_historico_ponto on public.sede_maturidade_historico (maturidade_id, valido_ate desc);
alter table public.sede_maturidade_historico enable row level security;
drop policy if exists "Equipe - sede_maturidade_historico" on public.sede_maturidade_historico;
create policy "Equipe - sede_maturidade_historico" on public.sede_maturidade_historico
  for select using (public.eh_staff());

create or replace function public.sede_maturidade_guardar_versao()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (old.situacao, old.dado, old.hipotese, old.observacao, old.onde, old.link)
     is distinct from (new.situacao, new.dado, new.hipotese, new.observacao, new.onde, new.link) then
    insert into public.sede_maturidade_historico (maturidade_id, situacao, dado, hipotese, observacao, onde, link, respondido_por)
    values (old.id, old.situacao, old.dado, old.hipotese, old.observacao, old.onde, old.link, old.respondido_por);
    -- Hora do banco, não do navegador: é ela que a rotina compara com sincronizado_em.
    new.atualizado_em := now();
  end if;
  return new;
end;
$$;
drop trigger if exists sede_maturidade_versao on public.sede_maturidade;
create trigger sede_maturidade_versao before update on public.sede_maturidade
  for each row execute function public.sede_maturidade_guardar_versao();

-- ── 3) Sugestões ───────────────────────────────────────────────────────
create table if not exists public.sede_maturidade_sugestoes (
  id bigint generated by default as identity primary key,
  maturidade_id bigint not null references public.sede_maturidade(id) on delete cascade,
  agente text not null,                             -- ester, rica, tati, carol, justa, honesta, claude...
  situacao text check (situacao is null or situacao in ('Sei explicar','Tem lacuna','Hipótese','A avaliar')),
  dado text, hipotese text, observacao text, onde text, link text,
  motivo text,
  status text not null default 'Pendente' check (status in ('Pendente','Aceita','Descartada')),
  criado_em timestamptz not null default now(),
  decidido_em timestamptz,
  decidido_por uuid
);
create index if not exists sede_maturidade_sugestoes_pend on public.sede_maturidade_sugestoes (maturidade_id) where status = 'Pendente';
alter table public.sede_maturidade_sugestoes enable row level security;
drop policy if exists "Equipe - sede_maturidade_sugestoes" on public.sede_maturidade_sugestoes;
create policy "Equipe - sede_maturidade_sugestoes" on public.sede_maturidade_sugestoes
  for all using (public.eh_staff()) with check (public.eh_staff());

-- ── 4) Leitura (agentes e rotina) ──────────────────────────────────────
create or replace function public.sede_maturidade_ler(p_chave text)
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
begin
  if not public.sede_chave_ok(p_chave) then
    raise exception 'chave inválida';
  end if;
  return jsonb_build_object(
    'pontos', coalesce((select jsonb_agg(jsonb_build_object(
        'id', m.id, 'ordem', m.ordem, 'ponto', m.ponto, 'pergunta', m.pergunta, 'situacao', m.situacao,
        'dado', m.dado, 'hipotese', m.hipotese, 'falta_verificar', m.observacao, 'onde', m.onde, 'link', m.link,
        'respondido_por', m.respondido_por, 'atualizado_em', m.atualizado_em,
        'sincronizado_em', m.sincronizado_em, 'drive_hash', m.drive_hash, 'tem_conflito', m.conflito_drive is not null
      ) order by m.ordem) from public.sede_maturidade m), '[]'::jsonb),
    'sugestoes_pendentes', coalesce((select jsonb_agg(jsonb_build_object(
        'ponto', m.ordem, 'agente', s.agente, 'criado_em', s.criado_em
      ) order by s.criado_em) from public.sede_maturidade_sugestoes s join public.sede_maturidade m on m.id = s.maturidade_id
       where s.status = 'Pendente'), '[]'::jsonb)
  );
end;
$$;
revoke all on function public.sede_maturidade_ler(text) from public;
grant execute on function public.sede_maturidade_ler(text) to anon, authenticated;

-- ── 5) Sugestão de agente ou do Claude ─────────────────────────────────
-- p = [{"ponto": 3, "agente": "ester", "situacao": "Tem lacuna", "dado": "...", "hipotese": "...",
--       "falta_verificar": "...", "onde": "...", "link": "...", "motivo": "por que sugere"}]
-- Uma sugestão pendente por agente e ponto: a nova substitui a anterior.
create or replace function public.sede_maturidade_sugerir(p_chave text, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  x jsonb;
  v_id bigint;
  v_agente text;
  v_n int := 0;
begin
  if not public.sede_chave_ok(p_chave) then
    raise exception 'chave inválida';
  end if;
  for x in select * from jsonb_array_elements(case when jsonb_typeof(p) = 'array' then p else '[]' end) loop
    select id into v_id from public.sede_maturidade where ordem = (x->>'ponto')::int;
    continue when v_id is null;
    v_agente := left(lower(coalesce(nullif(trim(x->>'agente'), ''), 'claude')), 20);
    delete from public.sede_maturidade_sugestoes where maturidade_id = v_id and agente = v_agente and status = 'Pendente';
    insert into public.sede_maturidade_sugestoes (maturidade_id, agente, situacao, dado, hipotese, observacao, onde, link, motivo)
    values (v_id, v_agente,
            case when x->>'situacao' in ('Sei explicar','Tem lacuna','Hipótese','A avaliar') then x->>'situacao' end,
            left(x->>'dado', 4000), left(x->>'hipotese', 4000), left(x->>'falta_verificar', 4000),
            left(x->>'onde', 500), left(x->>'link', 1000), left(x->>'motivo', 1500));
    v_n := v_n + 1;
  end loop;
  return jsonb_build_object('ok', true, 'sugestoes', v_n);
end;
$$;
revoke all on function public.sede_maturidade_sugerir(text, jsonb) from public;
grant execute on function public.sede_maturidade_sugerir(text, jsonb) to anon, authenticated;

-- ── 6) Sincronização com o Drive (rotina das 18h) ──────────────────────
-- p = [{"ponto": 3, "acao": "vem_do_drive" | "foi_pro_drive" | "conflito",
--       "drive_hash": "...", "campos": {situacao, dado, hipotese, falta_verificar, onde, link}}]
-- vem_do_drive: grava os campos do documento no CRM (respondido_por = "Documento no Drive").
-- foi_pro_drive: o documento foi reescrito com o CRM; só guarda a impressão digital.
-- conflito: guarda a versão do documento em conflito_drive; o CRM continua igual
--   (a rotina manda "conflito" e depois "foi_pro_drive", porque o documento é
--   reescrito com o CRM; a versão dele fica no CRM até ela decidir).
create or replace function public.sede_maturidade_sincronizar(p_chave text, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  x jsonb;
  c jsonb;
  v_agora timestamptz := now();
  v_n int := 0;
begin
  if not public.sede_chave_ok(p_chave) then
    raise exception 'chave inválida';
  end if;
  for x in select * from jsonb_array_elements(case when jsonb_typeof(p) = 'array' then p else '[]' end) loop
    c := coalesce(x->'campos', '{}'::jsonb);
    if x->>'acao' = 'vem_do_drive' then
      update public.sede_maturidade set
        situacao = case when c->>'situacao' in ('Sei explicar','Tem lacuna','Hipótese','A avaliar') then c->>'situacao' else situacao end,
        dado = nullif(left(c->>'dado', 4000), ''), hipotese = nullif(left(c->>'hipotese', 4000), ''),
        observacao = nullif(left(c->>'falta_verificar', 4000), ''),
        onde = nullif(left(c->>'onde', 500), ''), link = nullif(left(c->>'link', 1000), ''),
        respondido_por = 'Documento no Drive',
        atualizado_em = v_agora, sincronizado_em = v_agora, drive_hash = left(x->>'drive_hash', 128)
      where ordem = (x->>'ponto')::int;
    elsif x->>'acao' = 'conflito' then
      update public.sede_maturidade set conflito_drive = c || jsonb_build_object('em', v_agora)
      where ordem = (x->>'ponto')::int;
    elsif x->>'acao' = 'foi_pro_drive' then
      -- Só quando não ficou conflito aberto: senão, a próxima rotina perguntaria de novo.
      update public.sede_maturidade set sincronizado_em = greatest(atualizado_em, v_agora), drive_hash = left(x->>'drive_hash', 128)
      where ordem = (x->>'ponto')::int;
    else
      continue;
    end if;
    if found then v_n := v_n + 1; end if;
  end loop;
  return jsonb_build_object('ok', true, 'pontos', v_n);
end;
$$;
revoke all on function public.sede_maturidade_sincronizar(text, jsonb) from public;
grant execute on function public.sede_maturidade_sincronizar(text, jsonb) to anon, authenticated;

