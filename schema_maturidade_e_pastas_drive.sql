-- colar tudo → Run. Pode rodar de novo sem estragar nada.

-- ── 1) Maturidade ──────────────────────────────────────────────────────
create table if not exists public.sede_maturidade (
  id bigint generated by default as identity primary key,
  ordem int not null,
  ponto text not null unique,
  pergunta text,
  situacao text not null default 'A avaliar'
    check (situacao in ('Sei explicar','Tem lacuna','Hipótese','A avaliar')),
  onde text,                                     -- onde está a resposta (texto livre)
  link text,                                     -- link da resposta (doc, aba do CRM...)
  observacao text,
  atualizado_em timestamptz not null default now(),
  atualizado_por uuid default auth.uid()
);
alter table public.sede_maturidade enable row level security;
drop policy if exists "Equipe - sede_maturidade" on public.sede_maturidade;
create policy "Equipe - sede_maturidade" on public.sede_maturidade
  for all using (public.eh_staff()) with check (public.eh_staff());

