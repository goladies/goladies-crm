-- ── 2) Pastas do Drive ─────────────────────────────────────────────────
create table if not exists public.drive_pastas (
  id bigint generated by default as identity primary key,
  ordem int not null default 100,
  nome text not null unique,
  caminho text not null,                         -- onde fica no Drive (Meu Drive › ...)
  descricao text,
  link text,                                     -- link da pasta no Drive (colado pelo CRM)
  criado_em timestamptz not null default now()
);
alter table public.drive_pastas enable row level security;
drop policy if exists "Equipe - drive_pastas" on public.drive_pastas;
create policy "Equipe - drive_pastas" on public.drive_pastas
  for all using (public.eh_staff()) with check (public.eh_staff());

