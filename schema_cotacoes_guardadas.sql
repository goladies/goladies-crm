-- Arquivo: schema_cotacoes_guardadas.sql
-- Go Ladies: cotações guardadas do Simulador de preço (23/10/2026)
--
-- Antes: o Simulador guardava só a última cotação, no navegador.
-- Agora: o botão "Guardar cotação" grava a simulação aqui, com nome e (se
-- tiver) a cliente de viagem ou a lead. A lista "Cotações guardadas" mostra as dos últimos 30
-- dias; cada uma pode virar "viagem já feita", "pedido" ou "não aconteceu".
-- Passado o prazo, ela some da lista, mas a linha fica (é histórico de
-- cotação, serve pra ver quantas viraram viagem).
--
-- Só a equipe lê e edita (eh_staff).
--
-- Rodar uma vez em: Supabase (go-ladies-crm) → SQL Editor → New query →
-- colar tudo → Run. Pode rodar de novo sem estragar nada.

create table if not exists public.cotacoes_simulador (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now(),
  criado_por uuid default auth.uid(),
  nome text not null,
  cliente_id bigint references public.clientes_transporte(id) on delete set null,
  origem text,
  destino text,
  km numeric,
  minutos int,
  preco_tabela numeric,
  preco_cobrado numeric,
  repasse numeric,
  dados jsonb not null default '{}'::jsonb,   -- a tela do Simulador inteira, pra reabrir e lançar
  situacao text not null default 'Guardada'
    check (situacao in ('Guardada', 'Virou viagem', 'Virou pedido', 'Não aconteceu')),
  viagem_id bigint references public.viagens(id) on delete set null,
  resolvida_em timestamptz,
  expira_em timestamptz not null default now() + interval '30 days'
);

comment on column public.cotacoes_simulador.dados is
  'Campos do Simulador (endereços, km, minutos, tipo, tabela, noite, ida e volta, espera, cobrado, repasse)';
comment on column public.cotacoes_simulador.expira_em is
  'Até quando aparece na lista do Simulador (30 dias depois de guardada)';

-- Lead escolhida na cotação (23/10/2026): quem ainda não é cliente de
-- viagem. No "Aconteceu", o CRM cria a ficha de cliente de viagem e liga as
-- duas como mesma pessoa.
alter table public.cotacoes_simulador
  add column if not exists lead_id bigint references public.leads(id) on delete set null;

create index if not exists cotacoes_simulador_lista_idx
  on public.cotacoes_simulador (situacao, expira_em desc);

alter table public.cotacoes_simulador enable row level security;

drop policy if exists "Staff administra cotações guardadas" on public.cotacoes_simulador;
create policy "Staff administra cotações guardadas" on public.cotacoes_simulador
  for all using (public.eh_staff()) with check (public.eh_staff());

revoke all on public.cotacoes_simulador from anon;

select public.sql_registrar('schema_cotacoes_guardadas.sql');
