-- ── Quem e quando mudou (vale para as 5 tabelas) ────────────────────────
create or replace function public.servicos_planos_atualizado()
returns trigger language plpgsql as $$
begin
  new.atualizado_em := now();
  new.atualizado_por := coalesce(auth.jwt() ->> 'email', new.atualizado_por);
  return new;
end;
$$;

