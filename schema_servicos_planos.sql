-- ── Segurança e "quem mudou" nas 5 tabelas ──────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['catalogo_grupos', 'catalogo_servicos', 'planos_parceria', 'planos_beneficios', 'cotas_patrocinio'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Staff administra %s" on public.%I', t, t);
    execute format('create policy "Staff administra %s" on public.%I for all using (public.eh_staff()) with check (public.eh_staff())', t, t);
    execute format('drop trigger if exists %I on public.%I', t || '_atualizado', t);
    execute format('create trigger %I before insert or update on public.%I for each row execute function public.servicos_planos_atualizado()', t || '_atualizado', t);
  end loop;
end $$;

-- ── 6. Plano de cada parceira (o) ───────────────────────────────────────
alter table public.parceiros
  add column if not exists plano_id bigint references public.planos_parceria(id) on delete set null;

