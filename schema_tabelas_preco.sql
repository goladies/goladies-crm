-- Arquivo: schema_tabelas_preco.sql
-- Go Ladies: tabelas de preço por tipo de serviço e horário (21/10/2026)
--
-- Antes: o preço era fixo no código (R$ 25 por trecho + R$ 4/km, +30% de
-- madrugada ou feriado), igual pra qualquer viagem.
-- Agora: a Jú cadastra quantas tabelas quiser no CRM (Transporte ›
-- Financeiro do transporte › Tabelas de preço). Cada uma diz pra quem vale
-- (tipo de serviço ou todos), quando vale (dia, noite ou feriado, qualquer
-- horário) e os valores. Cada trecho (ida e volta) usa a tabela que mais
-- combina: tipo exato vale mais que "Todos"; dia/noite exato vale mais que
-- "Qualquer horário"; empate, a de menor ordem.
--   preço do trecho = maior entre (fixa + km × valor por km) e o mínimo,
--                     × (1 + adicional %)
--   motorista       = preço do trecho × (1 − taxa Go Ladies %)
-- As tabelas nascem com os valores de hoje: nenhum preço muda até ela editar.
-- Conta Adolescente pedindo como "Eu" usa a tabela de Adolescente.
--
-- 1) tabela tabelas_preco (só a equipe lê e edita) + as 5 tabelas iniciais
-- 2) viagens ganham qual tabela foi usada em cada trecho
-- 3) calcular_cotacao_tabela: a conta de um trecho
-- 4) calcular_cotacao antiga passa a usar as tabelas (mesmo formato)
-- 5) pedir_viagem_cliente usa o tipo de serviço (base: schema_distancia_ida_volta.sql)
--
-- Rodar uma vez em: Supabase (go-ladies-crm) → SQL Editor → New query →
-- colar tudo → Run. Pode rodar de novo sem estragar nada.

-- ── 1. Tabelas de preço ─────────────────────────────────────────────────
create table if not exists public.tabelas_preco (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo_servico text,                       -- null = todos os tipos
  quando text not null default 'qualquer'
    check (quando in ('dia', 'noite', 'qualquer')),
  tarifa_fixa numeric not null default 25 check (tarifa_fixa >= 0),
  valor_km numeric not null default 4 check (valor_km >= 0),
  valor_minimo numeric check (valor_minimo is null or valor_minimo >= 0),
  adicional_pct numeric not null default 0 check (adicional_pct >= 0),
  taxa_go_ladies_pct numeric not null default 25 check (taxa_go_ladies_pct between 0 and 100),
  ativa boolean not null default true,
  ordem int not null default 100,
  observacao text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

comment on column public.tabelas_preco.quando is
  'dia = 6h às 22h; noite = 22h às 6h ou feriado marcado na viagem; qualquer = os dois';

insert into public.tabelas_preco (nome, tipo_servico, quando, tarifa_fixa, valor_km, valor_minimo, adicional_pct, taxa_go_ladies_pct, ordem)
select * from (values
  ('Dia',                 null::text,    'dia',   25::numeric, 4::numeric, null::numeric, 0::numeric,  25::numeric, 10),
  ('Noite ou feriado',    null,          'noite', 25,          4,          null,          30,          25,          20),
  ('Criança (dia)',       'Criança',     'dia',   25,          4,          null,          0,           25,          30),
  ('Adolescente (dia)',   'Adolescente', 'dia',   25,          4,          null,          0,           25,          40),
  ('Idosa (o) (dia)',     'Idoso',       'dia',   25,          4,          null,          0,           25,          50)
) as v(nome, tipo_servico, quando, tarifa_fixa, valor_km, valor_minimo, adicional_pct, taxa_go_ladies_pct, ordem)
where not exists (select 1 from public.tabelas_preco);

alter table public.tabelas_preco enable row level security;

drop policy if exists "Staff administra tabelas de preço" on public.tabelas_preco;
create policy "Staff administra tabelas de preço" on public.tabelas_preco
  for all using (public.eh_staff()) with check (public.eh_staff());

create or replace function public.tabelas_preco_atualizado_em()
returns trigger language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;
drop trigger if exists tabelas_preco_atualizado_em on public.tabelas_preco;
create trigger tabelas_preco_atualizado_em before update on public.tabelas_preco
  for each row execute function public.tabelas_preco_atualizado_em();

-- ── 2. Qual tabela cada viagem usou ─────────────────────────────────────
alter table public.viagens
  add column if not exists tabela_preco_id bigint references public.tabelas_preco(id) on delete set null,
  add column if not exists tabela_preco_retorno_id bigint references public.tabelas_preco(id) on delete set null,
  add column if not exists tabela_preco_nome text,
  add column if not exists tabela_preco_escolhida boolean not null default false;

comment on column public.viagens.tabela_preco_nome is
  'Nome da tabela na hora da cotação (ex.: "Dia" ou "Dia / Noite ou feriado"), fica mesmo se a tabela mudar';
comment on column public.viagens.tabela_preco_escolhida is
  'true = a Jú escolheu a tabela na mão no CRM; false = automática pelo tipo e horário';

-- ── 3. Conta de um trecho ───────────────────────────────────────────────
create or replace function public.calcular_cotacao_tabela(
  p_distancia_km numeric,
  p_noturno boolean,
  p_tipo_servico text default null
)
returns table (
  tabela_id bigint,
  tabela_nome text,
  tarifa_fixa numeric,
  valor_km numeric,
  adicional_pct numeric,
  preco_cotado numeric,
  preco_motorista numeric
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  t public.tabelas_preco;
  v_valor numeric;
begin
  select * into t
    from public.tabelas_preco tp
   where tp.ativa
     and (tp.tipo_servico is null or tp.tipo_servico = p_tipo_servico)
     and (tp.quando = 'qualquer' or tp.quando = case when coalesce(p_noturno, false) then 'noite' else 'dia' end)
   order by (tp.tipo_servico is not null) desc, (tp.quando <> 'qualquer') desc, tp.ordem, tp.id
   limit 1;

  if t.id is null then
    -- Nenhuma tabela ativa serve: vale a regra antiga, pra cotação nunca ficar sem preço.
    t.tarifa_fixa := 25; t.valor_km := 4; t.valor_minimo := null;
    t.adicional_pct := case when coalesce(p_noturno, false) then 30 else 0 end;
    t.taxa_go_ladies_pct := 25; t.nome := 'Padrão do sistema';
  end if;

  v_valor := greatest(t.tarifa_fixa + t.valor_km * coalesce(p_distancia_km, 0), coalesce(t.valor_minimo, 0))
             * (1 + t.adicional_pct / 100);

  return query select t.id, t.nome, t.tarifa_fixa, t.valor_km, t.adicional_pct,
                      round(v_valor, 2), round(v_valor * (1 - t.taxa_go_ladies_pct / 100), 2);
end;
$$;

revoke execute on function public.calcular_cotacao_tabela(numeric, boolean, text) from public, anon;
grant execute on function public.calcular_cotacao_tabela(numeric, boolean, text) to authenticated, service_role;

-- ── 4. Função antiga, mesmo formato, agora pelas tabelas ────────────────
create or replace function public.calcular_cotacao(
  p_distancia_km numeric,
  p_horario time
)
returns table (
  tarifa_fixa numeric,
  valor_km numeric,
  adicional_noturno boolean,
  preco_cotado numeric,
  preco_motorista numeric
)
language sql
stable
security definer
set search_path = public
as $$
  select c.tarifa_fixa, c.valor_km,
         (p_horario is not null and (p_horario >= '22:00' or p_horario < '06:00')),
         c.preco_cotado, c.preco_motorista
    from public.calcular_cotacao_tabela(
           p_distancia_km,
           (p_horario is not null and (p_horario >= '22:00' or p_horario < '06:00')),
           'Padrão') c;
$$;

grant execute on function public.calcular_cotacao(numeric, time) to authenticated, service_role;

-- ── 5. Pedido pelo app: tabela pelo tipo de serviço ─────────────────────
-- Igual ao schema_distancia_ida_volta.sql; muda só a conta do preço e
-- guarda a tabela usada em cada trecho.
create or replace function public.pedir_viagem_cliente(
  p_tipo_servico text,
  p_origem text,
  p_destino text,
  p_data date,
  p_horario time,
  p_data_retorno date default null,
  p_horario_retorno time default null,
  p_origem_retorno text default null,
  p_destino_retorno text default null,
  p_motorista_preferida boolean default false,
  p_observacoes text default null,
  p_distancia_km numeric default null,
  p_duracao_min numeric default null,
  p_origem_lat double precision default null,
  p_origem_lng double precision default null,
  p_paradas jsonb default null,
  p_distancia_km_retorno numeric default null,
  p_duracao_min_retorno numeric default null
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cliente_id bigint := public.cliente_id_atual();
  v_id bigint;
  v_tem_volta boolean := p_data_retorno is not null and p_horario_retorno is not null;
  v_tem_km boolean := p_distancia_km is not null and p_distancia_km > 0;
  v_tem_km_volta boolean;
  v_area public.areas_atendimento;
  v_antecedencia int := 60;
  v_tarifa_fixa numeric;
  v_valor_km numeric;
  v_noturno boolean := false;
  v_preco_cotado numeric;
  v_preco_motorista numeric;
  v_noturno_volta boolean := false;
  v_preco_volta numeric;
  v_motorista_volta numeric;
  v_fixo_volta numeric;
  v_paradas jsonb := case when jsonb_typeof(p_paradas) = 'array' then p_paradas else '[]'::jsonb end;
  v_tipo text := coalesce(nullif(btrim(coalesce(p_tipo_servico, '')), ''), 'Padrão');
  v_tipo_preco text;
  v_tab_ida bigint;
  v_tab_volta bigint;
  v_nome_ida text;
  v_nome_volta text;
begin
  v_tem_km_volta := v_tem_volta and p_distancia_km_retorno is not null and p_distancia_km_retorno > 0;

  if v_cliente_id is null then
    raise exception 'Login não vinculado a nenhuma cliente.';
  end if;
  if nullif(btrim(coalesce(p_origem, '')), '') is null or nullif(btrim(coalesce(p_destino, '')), '') is null then
    raise exception 'Informe de onde e para onde.';
  end if;
  if p_data is null or p_horario is null then
    raise exception 'Informe data e horário.';
  end if;
  if jsonb_array_length(v_paradas) > 8 then
    raise exception 'No máximo 8 paradas por viagem.';
  end if;

  if p_origem_lat is not null and p_origem_lng is not null then
    select * into v_area from public.area_atendimento_de(p_origem_lat, p_origem_lng);
    if v_area.id is null then
      raise exception 'FORA_DA_AREA';
    end if;
    v_antecedencia := coalesce(v_area.antecedencia_minima_min, 60);
  end if;

  if (p_data + p_horario) < ((now() at time zone 'America/Sao_Paulo') + make_interval(mins => v_antecedencia)) then
    raise exception 'ANTECEDENCIA_MINIMA:%', v_antecedencia;
  end if;

  if v_tem_volta and (p_data_retorno + p_horario_retorno) < (p_data + p_horario) then
    raise exception 'O retorno precisa ser depois da ida.';
  end if;

  -- Conta Adolescente pedindo pra ela mesma vem como "Padrão": cota como Adolescente.
  v_tipo_preco := v_tipo;
  if v_tipo = 'Padrão' and coalesce((select public.idade_anos(c.aniversario) from public.clientes_transporte c where c.id = v_cliente_id), 99) < 18 then
    v_tipo_preco := 'Adolescente';
  end if;

  if v_tem_km then
    v_noturno := (p_horario >= '22:00' or p_horario < '06:00');
    select c.tarifa_fixa, c.valor_km, c.preco_cotado, c.preco_motorista, c.tabela_id, c.tabela_nome
      into v_tarifa_fixa, v_valor_km, v_preco_cotado, v_preco_motorista, v_tab_ida, v_nome_ida
      from public.calcular_cotacao_tabela(round(p_distancia_km, 1), v_noturno, v_tipo_preco) c;

    if v_tem_volta then
      v_noturno_volta := (p_horario_retorno >= '22:00' or p_horario_retorno < '06:00');
      select c.tarifa_fixa, c.preco_cotado, c.preco_motorista, c.tabela_id, c.tabela_nome
        into v_fixo_volta, v_preco_volta, v_motorista_volta, v_tab_volta, v_nome_volta
        from public.calcular_cotacao_tabela(case when v_tem_km_volta then round(p_distancia_km_retorno, 1) else 0 end, v_noturno_volta, v_tipo_preco) c;
      v_preco_cotado := v_preco_cotado + v_preco_volta;
      v_preco_motorista := v_preco_motorista + v_motorista_volta;
      if not v_tem_km_volta then
        v_tarifa_fixa := v_tarifa_fixa + v_fixo_volta;
      end if;
    end if;
  end if;

  insert into public.viagens (
    cliente_id, tipo_servico, canal_recepcao, origem_endereco, destino_endereco,
    data, horario_partida, data_retorno, horario_retorno,
    origem_retorno_endereco, destino_retorno_endereco,
    motorista_preferida, observacoes_cliente,
    distancia_km, duracao_prevista_min,
    distancia_km_retorno, duracao_prevista_retorno_min,
    origem_lat, origem_lng,
    tarifa_fixa, valor_km, adicional_noturno, adicional_noturno_retorno,
    preco_cotado, preco_motorista,
    tabela_preco_id, tabela_preco_retorno_id, tabela_preco_nome,
    status
  )
  values (
    v_cliente_id,
    v_tipo,
    'Painel da cliente',
    btrim(p_origem), btrim(p_destino),
    p_data, p_horario, p_data_retorno, p_horario_retorno,
    nullif(btrim(coalesce(p_origem_retorno, '')), ''),
    nullif(btrim(coalesce(p_destino_retorno, '')), ''),
    coalesce(p_motorista_preferida, false),
    nullif(btrim(coalesce(p_observacoes, '')), ''),
    case when v_tem_km then round(p_distancia_km, 1) end,
    case when v_tem_km and p_duracao_min is not null then round(p_duracao_min) end,
    case when v_tem_km and v_tem_km_volta then round(p_distancia_km_retorno, 1) end,
    case when v_tem_km and v_tem_km_volta and p_duracao_min_retorno is not null then round(p_duracao_min_retorno) end,
    p_origem_lat, p_origem_lng,
    v_tarifa_fixa,
    v_valor_km,
    coalesce(v_noturno, false),
    coalesce(v_noturno_volta, false),
    v_preco_cotado,
    v_preco_motorista,
    v_tab_ida,
    v_tab_volta,
    case when v_nome_volta is null or v_nome_volta = v_nome_ida then v_nome_ida
         else v_nome_ida || ' / ' || v_nome_volta end,
    case when v_tem_km then 'Cotando preço' else 'Solicitada' end
  )
  returning id into v_id;

  insert into public.viagem_paradas (viagem_id, ordem, tipo, endereco, passageira_nome)
  select v_id,
         row_number() over (order by p.idx),
         'Parada',
         left(btrim(p.item->>'endereco'), 300),
         left(nullif(btrim(coalesce(p.item->>'passageira_nome', '')), ''), 80)
    from jsonb_array_elements(v_paradas) with ordinality as p(item, idx)
   where nullif(btrim(coalesce(p.item->>'endereco', '')), '') is not null;

  return v_id;
end;
$$;

revoke execute on function public.pedir_viagem_cliente(text, text, text, date, time, date, time, text, text, boolean, text, numeric, numeric, double precision, double precision, jsonb, numeric, numeric) from public, anon;
grant execute on function public.pedir_viagem_cliente(text, text, text, date, time, date, time, text, text, boolean, text, numeric, numeric, double precision, double precision, jsonb, numeric, numeric) to authenticated;

